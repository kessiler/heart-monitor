const storageKey = 'heart-monitor-locale';
let locale = 'pt';
try {
  const saved = globalThis.localStorage?.getItem(storageKey);
  if (saved === 'pt' || saved === 'en') locale = saved;
} catch {
  // Private browsing or storage policy can prevent persistence.
}

export function getLocale() {
  return locale;
}

export function t(key, values = {}) {
  const message = translations[locale][key] ?? translations.pt[key] ?? key;
  return message.replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match,
  );
}

export function applyLocale() {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = locale === 'pt' ? 'pt-BR' : 'en';
  document.title = t('page.title');
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('page.description'));
  document.querySelector('meta[property="og:title"]')?.setAttribute('content', t('page.title'));
  document.querySelector('meta[property="og:description"]')?.setAttribute('content', t('page.socialDescription'));
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  ['aria-label', 'title', 'placeholder', 'alt'].forEach((attribute) => {
    document.querySelectorAll(`[data-i18n-${attribute}]`).forEach((element) => {
      element.setAttribute(attribute, t(element.getAttribute(`data-i18n-${attribute}`)));
    });
  });
}

export function setLocale(nextLocale) {
  if (nextLocale !== 'pt' && nextLocale !== 'en') return;
  locale = nextLocale;
  try {
    globalThis.localStorage?.setItem(storageKey, locale);
  } catch {
    // The interface still switches when preference storage is unavailable.
  }
  applyLocale();
  if (typeof window !== 'undefined') {
    window.dispatchEvent(new CustomEvent('localechange', { detail: { locale } }));
  }
}
